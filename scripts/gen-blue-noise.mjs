// Generates a blue-noise threshold texture via the void-and-cluster algorithm
// (Ulichney 1993) and writes it as an inline base64 data module.
//
// Offline, one-time, run manually when SIZE changes - not part of the build.
// This is the one place in the project baking is preferred over a runtime
// formula: blue noise's whole value is that every neighborhood of the texture
// has a well-distributed spread of ranks, which a per-pixel hash cannot give
// you cheaply, and computing void-and-cluster in a shader is not practical.
import { writeFileSync } from 'node:fs';

const SIZE = 64;
const N = SIZE * SIZE;
const SIGMA = 1.5;
const RADIUS = Math.ceil(SIGMA * 3);

const offsets = [];
for (let dy = -RADIUS; dy <= RADIUS; dy++) {
  for (let dx = -RADIUS; dx <= RADIUS; dx++) {
    offsets.push([dx, dy, Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA))]);
  }
}

const idx = (x, y) => ((y + SIZE) % SIZE) * SIZE + ((x + SIZE) % SIZE);

function makeDensity() {
  return new Float64Array(N);
}
function addPoint(density, x, y, sign) {
  for (const [dx, dy, w] of offsets) density[idx(x + dx, y + dy)] += sign * w;
}
function argmax(pattern, density, want) {
  let best = -1;
  let bestVal = -Infinity;
  for (let i = 0; i < N; i++) if (pattern[i] === want && density[i] > bestVal) { bestVal = density[i]; best = i; }
  return best;
}
function argmin(pattern, density, want) {
  let best = -1;
  let bestVal = Infinity;
  for (let i = 0; i < N; i++) if (pattern[i] === want && density[i] < bestVal) { bestVal = density[i]; best = i; }
  return best;
}

// Phase 1: seed an initial binary pattern (~10% ones) and relax it by
// repeatedly swapping the tightest cluster for the tightest void.
const initialCount = Math.max(1, Math.round(N * 0.1));
const all = [...Array(N).keys()];
for (let i = all.length - 1; i > 0; i--) {
  const j = Math.floor(Math.random() * (i + 1));
  [all[i], all[j]] = [all[j], all[i]];
}
const pattern = new Uint8Array(N);
const density = makeDensity();
for (const id of all.slice(0, initialCount)) {
  pattern[id] = 1;
  addPoint(density, id % SIZE, Math.floor(id / SIZE), 1);
}
for (let iter = 0; iter < initialCount * 2; iter++) {
  const c = argmax(pattern, density, 1);
  pattern[c] = 0;
  addPoint(density, c % SIZE, Math.floor(c / SIZE), -1);
  const v = argmin(pattern, density, 0);
  pattern[v] = 1;
  addPoint(density, v % SIZE, Math.floor(v / SIZE), 1);
  if (v === c) break;
}

// Phase 2: rank the initial pattern's points downward by peeling off the
// tightest cluster one at a time (assigns ranks initialCount-1 .. 0).
const ranks = new Int32Array(N).fill(-1);
{
  const p = pattern.slice();
  const d = density.slice();
  let rank = initialCount - 1;
  while (rank >= 0) {
    const best = argmax(p, d, 1);
    ranks[best] = rank--;
    p[best] = 0;
    addPoint(d, best % SIZE, Math.floor(best / SIZE), -1);
  }
}

// Phase 3: rank everything above the initial pattern upward by filling the
// tightest void one at a time (assigns ranks initialCount .. N-1).
{
  const p = pattern.slice();
  const d = density.slice();
  let rank = initialCount;
  while (rank < N) {
    const best = argmin(p, d, 0);
    ranks[best] = rank++;
    p[best] = 1;
    addPoint(d, best % SIZE, Math.floor(best / SIZE), 1);
  }
}

// Each texel now holds a unique rank 0..N-1; normalize to a threshold 0..255.
const bytes = new Uint8Array(N);
for (let i = 0; i < N; i++) bytes[i] = Math.round((ranks[i] / (N - 1)) * 255);

const b64 = Buffer.from(bytes).toString('base64');

const out = `// Generated by scripts/gen-blue-noise.mjs - do not hand-edit.
// ${SIZE}x${SIZE} single-channel (R8) blue-noise threshold texture, void-and-cluster.
export const BLUE_NOISE_SIZE = ${SIZE};
export const BLUE_NOISE_B64 = '${b64}';
`;

writeFileSync(new URL('../src/render/blueNoise.data.ts', import.meta.url), out);
console.log(`wrote src/render/blueNoise.data.ts (${SIZE}x${SIZE}, ${bytes.length} bytes -> ${b64.length} b64 chars)`);
